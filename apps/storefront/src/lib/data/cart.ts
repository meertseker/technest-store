/**
 * One backend read per page render: the layout, the header and the page all ask
 * for the same basket. (Calls with a deadline are not de-duplicated by Next.)
 * Outside a render (form actions, route handlers) every call reads again.
 */
const readCart = cache(async (id: string, fields: string): Promise<HttpTypes.StoreCart | null> => {
  const headers = {
    ...(await getAuthHeaders()),
  }

  try {
    // A basket belongs to one visitor and changes outside this app (the payment
    // webhook completes it), so it is read fresh and never stored.
    const { cart } = await sdk.client.fetch<HttpTypes.StoreCartResponse>(`/store/carts/${id}`, {
      method: "GET",
      query: {
        fields,
      },
      headers,
      cache: "no-store",
    })
    return cart
  } catch (error) {
    if ((error as { status?: number } | null)?.status === 404) return null
    // callers show their own message; this is the one place that sees every failed read
    await reportError(error, "basket.read")
    throw error
  }
})

/**
 * The shopper's basket (the cart from the cookie, or `cartId`).
 *
 * null means there is no basket: no cookie, the backend says the cart does not
 * exist, or the cart has already become an order (the payment webhook completes
 * it when the shopper closes the tab after paying). Any other failure is
 * thrown: a backend that cannot answer is not an empty basket, and callers must
 * not replace the cookie or show "your basket is empty" because of it.
 */
export async function retrieveCart(
  cartId?: string,
  fields?: string,
  options?: { includeCompleted?: boolean }
) {
  const id = cartId || (await getCartId())
  fields ??=
    "*items, *region, *items.product, *items.variant, *items.thumbnail, *items.metadata, +items.total, *promotions, +shipping_methods.name"

  if (!id) {
    return null
  }

  const cart = await readCart(id, fields)
  if (!cart) return null

  const completedAt = (cart as { completed_at?: string | null }).completed_at
  if (completedAt && !options?.includeCompleted) return null
  return cart
}

export async function getOrSetCart(countryCode: string) {
  const region = await getRegion(countryCode)

  if (!region) {
    throw new Error(`Region not found for country code: ${countryCode}`)
  }

  // A missing or completed basket is replaced below; if the backend fails this
  // throws, so a bad moment never swaps the shopper's basket for an empty one.
  let cart = await retrieveCart(undefined, "id,region_id,completed_at")

  const headers = {
    ...(await getAuthHeaders()),
  }

  if (!cart) {
    const locale = await getLocale()
    const cartResp = await sdk.store.cart.create(
      { region_id: region.id, locale: locale || undefined },
      {},
      headers
    )
    cart = cartResp.cart

    await setCartId(cart.id)

    const cartCacheTag = await getCacheTag("carts")
    revalidateTag(cartCacheTag)
  }

  if (cart && cart?.region_id !== region.id) {
    await sdk.store.cart.update(cart.id, { region_id: region.id }, {}, headers)
    const cartCacheTag = await getCacheTag("carts")
    revalidateTag(cartCacheTag)
  }

  return cart
}

export async function updateCart(data: HttpTypes.StoreUpdateCart) {
  const cartId = await getCartId()

  if (!cartId) {
    throw new Error("No existing cart found, please create one before updating")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  return sdk.store.cart
    .update(cartId, data, {}, headers)
    .then(async ({ cart }: { cart: HttpTypes.StoreCart }) => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      revalidateTag(fulfillmentCacheTag)

      return cart
    })
    .catch(medusaError)
}

export async function addToCart({
  variantId,
  quantity,
  countryCode,
}: {
  variantId: string
  quantity: number
  countryCode: string
}) {
  if (!variantId) {
    throw new Error("Missing variant ID when adding to cart")
  }

  const cart = await getOrSetCart(countryCode)

  if (!cart) {
    throw new Error("Error retrieving or creating cart")
  }

  const headers = {
    ...(await getAuthHeaders()),
  }

  await sdk.store.cart
    .createLineItem(
      cart.id,
      {
        variant_id: variantId,
        quantity,
      },
      {},
      headers
    )
    .then(async () => {
      const cartCacheTag = await getCacheTag("carts")
      revalidateTag(cartCacheTag)

      const fulfillmentCacheTag = await getCacheTag("fulfillment")
      revalidateTag(fulfillmentCacheTag)
    })
    .catch(medusaError)
}

